// Regenerates netlify.toml and public/_headers (publish dir, redirects, security headers incl. CSP hashes)
// from the inline <script> blocks in public/*.html.
//   node tools/build-config.mjs          -> writes netlify.toml
//   node tools/build-config.mjs --check  -> exits 1 if netlify.toml is out of date
// RUN THIS AFTER ANY EDIT TO AN INLINE <script> IN public/*.html, otherwise the browser
// will refuse to run the changed script (that is the point of hash-based CSP).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const hashes = (file) => {
  const html = readFileSync(join(root, 'public', file), 'utf8');
  const out = [];
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    out.push(`'sha256-${createHash('sha256').update(m[1], 'utf8').digest('base64')}'`);
  }
  return out;
};
const csp = (file) => [
  "default-src 'self'",
  `script-src 'self' ${hashes(file).join(' ')}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-src 'none'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "object-src 'none'"
].join('; ');

const common = (extra = '') => `    X-Content-Type-Options = "nosniff"
    X-Frame-Options = "DENY"
    Referrer-Policy = "strict-origin-when-cross-origin"
    Strict-Transport-Security = "max-age=31536000"
    Permissions-Policy = "camera=(), microphone=(), geolocation=(), payment=()"${extra}`;
const block = (path, file, extra = '') => `[[headers]]
  for = "${path}"
  [headers.values]
${common(extra)}
    Content-Security-Policy = "${csp(file)}"
`;

const toml = `# GENERATED by tools/build-config.mjs — do not edit by hand.
# Deploy with Git or the Netlify CLI so this file is honoured (see docs/DEPLOYMENT-GUIDE-V1.2.1.md).
[build]
  publish = "public"
  functions = "netlify/functions"

[functions]
  node_bundler = "esbuild"

# Defence in depth: if the project root were ever published by mistake, these stay private.
[[redirects]]
  from = "/netlify/*"
  to = "/index.html"
  status = 404
  force = true
[[redirects]]
  from = "/docs/*"
  to = "/index.html"
  status = 404
  force = true
[[redirects]]
  from = "/tests/*"
  to = "/index.html"
  status = 404
  force = true
[[redirects]]
  from = "/tools/*"
  to = "/index.html"
  status = 404
  force = true
[[redirects]]
  from = "/package.json"
  to = "/index.html"
  status = 404
  force = true
[[redirects]]
  from = "/netlify.toml"
  to = "/index.html"
  status = 404
  force = true

# Public site
${block('/', 'index.html')}
${block('/index.html', 'index.html')}
# Admin page: never cached, never indexed
${block('/admin', 'admin.html', '\n    X-Robots-Tag = "noindex, nofollow"\n    Cache-Control = "no-store"')}
${block('/admin.html', 'admin.html', '\n    X-Robots-Tag = "noindex, nofollow"\n    Cache-Control = "no-store"')}`;

// Cloudflare Pages reads public/_headers. It MUST carry the same CSP hashes, otherwise the
// browser blocks the inline admin script and the login button silently does nothing.
const cfCommon = `  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()`;
const cfAdmin = `
  X-Robots-Tag: noindex, nofollow
  Cache-Control: no-store`;
const cfBlock = (path, file, extra = '') => `${path}
${cfCommon}${extra}
  Content-Security-Policy: ${csp(file)}
`;
const cfHeaders = `# Cloudflare Pages static response headers; CSP hashes mirrored from generated netlify.toml.
# GENERATED by tools/build-config.mjs — do not edit by hand.

${cfBlock('/', 'index.html')}
${cfBlock('/index.html', 'index.html')}
${cfBlock('/admin', 'admin.html', cfAdmin)}
${cfBlock('/admin.html', 'admin.html', cfAdmin)}`;

const outputs = [[join(root, 'netlify.toml'), toml], [join(root, 'public', '_headers'), cfHeaders]];
if (process.argv.includes('--check')) {
  let stale = false;
  for (const [file, text] of outputs) {
    if (readFileSync(file, 'utf8') !== text) { console.error(`${file.slice(root.length + 1)} is out of date: run node tools/build-config.mjs`); stale = true; }
  }
  if (stale) process.exit(1);
  console.log('netlify.toml and public/_headers up to date');
} else { for (const [file, text] of outputs) writeFileSync(file, text); console.log('wrote netlify.toml and public/_headers'); }
